function josue() {
    const a = document.getElementsByClassName("josue-info")[0]
    const b = document.getElementsByClassName("josue-galery")[0]
    if (a.style.display==="none" && b.style.display==="none"){
        a.style.display="flex";
        b.style.display="flex";
    }else{
        a.style.display="none";
        b.style.display="none";        
    }
}
const bjosue = document.getElementsByClassName("josue")[0]
bjosue.addEventListener("click",josue)

