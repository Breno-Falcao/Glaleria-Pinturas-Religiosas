function jo() {
    const a = document.getElementsByClassName("jo-info")[0]
    const b = document.getElementsByClassName("jo-galery")[0]
    if (a.style.display==="none" && b.style.display==="none"){
        a.style.display="flex";
        b.style.display="flex";
    }else{
        a.style.display="none";
        b.style.display="none";        
    }
}
const bjo = document.getElementsByClassName("jo")[0]
bjo.addEventListener("click",jo)

