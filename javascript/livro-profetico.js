function isaias() {
    const a = document.getElementsByClassName("isaias-info")[0]
    const b = document.getElementsByClassName("isaias-galery")[0]
    if (a.style.display==="none" && b.style.display==="none"){
        a.style.display="flex";
        b.style.display="flex";
    }else{
        a.style.display="none";
        b.style.display="none";        
    }
}
const bisaias = document.getElementsByClassName("isaias")[0]
bisaias.addEventListener("click",isaias)

