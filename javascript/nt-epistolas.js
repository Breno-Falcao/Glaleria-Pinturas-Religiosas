function romanos() {
    const a = document.getElementsByClassName("romanos-info")[0]
    const b = document.getElementsByClassName("romanos-galery")[0]
    if (a.style.display==="none" && b.style.display==="none"){
        a.style.display="flex";
        b.style.display="flex";
    }else{
        a.style.display="none";
        b.style.display="none";        
    }
}
const bromanos = document.getElementsByClassName("romanos")[0]
bromanos.addEventListener("click",romanos)

